import { createRequire } from 'node:module'
import { mkdir, writeFile } from 'node:fs/promises'
import assert from 'node:assert/strict'
const require = createRequire(import.meta.url)
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const output = new URL('../../../docs/office-rebuild-evidence/', import.meta.url)
await mkdir(output, { recursive: true })
const browser = await chromium.launch({ channel: 'chrome', headless: true })
const errors = []
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
  page.on('pageerror', (e) => errors.push(e.message))
  await page.route('**/api/**', (route) => route.fulfill({ json: [] }))
  await page.routeWebSocket(/\/ws/, () => {})
  await page.goto(`${process.env.OFFICE_URL || 'http://127.0.0.1:5174'}/office`)
  await page.getByText('A day at the office', { exact: true }).waitFor()
  // Isolate rendering from external stream updates; fixtures enter through the real store.
  await page.evaluate(async () => {
    const { useSim } = await import('/src/stores/simStore.ts')
    const { RAW_EMPLOYEES } = await import('/src/game/engine/EmployeeCatalog.ts')
    const avatars = Object.fromEntries(RAW_EMPLOYEES.map(([id, name, role, team], i) => [id, { employee_id: id, name, role, team, fsm: i === 10 ? 'blocked' : i === 6 || i === 3 ? 'waiting' : 'working', badge: 'none', sprite_key: '', tile: { x: 0, y: 0 }, facing: 's', risk_score: 0, status: 'active', current_task_title: 'Visual check fixture' }]))
    useSim.setState({ avatars, error: null })
    const { useTelemetry } = await import('/src/stores/telemetryStore.ts')
    useTelemetry.setState({ connected: true })
  })
  const scene = page.getByLabel('Interactive live office simulation', { exact: true })
  const lifeTime = async () => Number(await scene.getAttribute('data-life-time'))
  const before = await lifeTime()
  await page.waitForTimeout(400)
  assert(await lifeTime() > before, 'animation clock should advance')
  await page.getByRole('button', { name: 'Wave hello', exact: true }).click()
  await page.waitForTimeout(100)
  await page.screenshot({ path: new URL('office-life-wave.png', output).pathname })
  await page.getByRole('button', { name: 'Pause life', exact: true }).click()
  const paused = await lifeTime()
  await page.waitForTimeout(150)
  assert.equal(await lifeTime(), paused, 'local pause freezes life')
  await page.getByRole('button', { name: 'Resume life', exact: true }).click()
  await page.evaluate(async () => { const { useSim } = await import('/src/stores/simStore.ts'); useSim.setState({ speed: 0 }) })
  await page.waitForTimeout(50)
  const globalPaused = await lifeTime()
  await page.waitForTimeout(150)
  assert.equal(await lifeTime(), globalPaused, 'simulation pause freezes life')
  await page.evaluate(async () => { const { useSim } = await import('/src/stores/simStore.ts'); useSim.setState({ speed: 1 }) })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.getByRole('button', { name: 'Reduced motion', exact: true }).waitFor()
  const reduced = await lifeTime()
  await page.waitForTimeout(150)
  assert.equal(await lifeTime(), reduced, 'reduced motion freezes life')
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.getByRole('button', { name: 'Pause life', exact: true }).click()
  for (const [width, height] of [[1280, 720], [1440, 900], [1920, 1080]]) {
    await page.setViewportSize({ width, height }); await page.waitForTimeout(150)
    await page.getByLabel('Office status counts').getByText('Blocked 1').waitFor()
    await page.screenshot({ path: new URL(`reference-${width}x${height}.png`, output).pathname })
    const rects = await page.getByLabel('Employee nameplates').getByRole('button').evaluateAll((nodes) => nodes.map((n) => { const r = n.getBoundingClientRect(); return { x: r.x, y: r.y, right: r.right, bottom: r.bottom } }))
    assert(rects.every((r) => r.x >= 0 && r.y >= 0 && r.right <= width && r.bottom <= height))
    for (let i = 0; i < rects.length; i++) for (let j = i + 1; j < rects.length; j++) {
      const a = rects[i], b = rects[j]; assert(!(a.x < b.right && a.right > b.x && a.y < b.bottom && a.bottom > b.y), 'nameplates overlap')
    }
  }
  await page.getByRole('button', { name: 'System log', exact: true }).click()
  await page.getByRole('heading', { name: 'SYSTEM LOG', exact: true }).waitFor()
  await page.getByRole('button', { name: 'Hide system log', exact: true }).click()
  await page.getByLabel('Focus room').selectOption('dev_floor')
  await page.getByRole('button', { name: 'Zoom in', exact: true }).click()
  await page.getByRole('button', { name: 'Fit', exact: true }).click()
  await page.screenshot({ path: new URL('reference-development-focus.png', output).pathname })
  await page.getByLabel('Select employee', { exact: true }).selectOption('emp_013')
  assert(new URL(page.url()).searchParams.get('employee') === 'emp_013')
  await page.getByRole('button', { name: 'Close', exact: true }).waitFor()
  await page.keyboard.press('Escape')
  await page.waitForURL((url) => !url.searchParams.has('employee'))
  await page.getByLabel('Focus room').selectOption('all')
  await page.getByLabel('Select employee', { exact: true }).selectOption('')
  await page.getByRole('button', { name: 'Names', exact: true }).focus(); await page.keyboard.press('Enter')
  assert.equal(await page.getByRole('button', { name: 'Names', exact: true }).getAttribute('aria-pressed'), 'false')
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.evaluate(async () => {
    const { useSim } = await import('/src/stores/simStore.ts')
    useSim.setState((s) => ({ avatars: { emp_004: { ...s.avatars.emp_004, fsm: 'blocked' } } }))
  })
  await page.getByLabel('Office status counts').getByText('Blocked 1').waitFor()
  assert.equal(await page.locator('#office-employee option').count(), 2)
  await page.evaluate(async () => { const { useSim } = await import('/src/stores/simStore.ts'); useSim.setState({ avatars: {} }) })
  await page.getByText('Layout preview · waiting for live employee telemetry').waitFor()
  assert(await page.getByLabel('Select employee', { exact: true }).isDisabled())
  assert.deepEqual(errors, [])
  await writeFile(new URL('reference-check.json', output), JSON.stringify({ passed: ['animation clock', 'wave interaction', 'local/global pause', 'reduced motion freeze', 'three viewport sizes', 'non-overlapping labels', 'room focus', 'zoom/fit', 'employee selection/drawer/Escape', 'system log toggle', 'keyboard names toggle', 'reduced-motion render', 'store status change/removal', 'empty telemetry preview'], pageErrors: errors }, null, 2) + '\n')
  console.log('Reference office browser checks passed.')
} finally { await browser.close() }
