/**
 * Room background loader and world-bounds calculator.
 *
 * Loads 5 pre-rendered room background PNGs (one per room) instead of
 * drawing walls, floors, and props procedurally. The dynamic overlay
 * layer (avatars, halos, name plates) is drawn on top by OfficeSimulation.
 */

import {
  WALL_H,
  iso,
  depth,
} from './IsoMath'
import type { RoomSpec } from '../systems/Types'

/**
 * Room layout: one compact tower block (a 32x32 footprint, L-shaped):
 *
 *   y 0-20:  dev_floor (x 0-20)   | managers (20-32, y 0-7) | ceo (20-30, y 7-15)
 *                                  | devops  (20-30, y 15-23)
 *   y 20-32: meeting_room (x 0-16)
 *
 * Rooms sit edge-to-edge; each room's art carries its own N and W wall
 * strips, and depth order (iso tx+ty) paints the right-hand rooms' W walls
 * over the neighbor's floor — so shared boundaries read as interior walls.
 */
export const ROOMS: RoomSpec[] = [
  { id: 'dev_floor', label: 'DEVELOPMENT FLOOR', o: [0, 0], s: [20, 20], floor: ['#C7B698', '#C0AE90'], labelAt: [10, 18] },
  { id: 'managers', label: 'MANAGERS', o: [20, 0], s: [12, 11], floor: ['#4B6578', '#456073'], labelAt: [26, 8.5] },
  { id: 'ceo_office', label: 'CEO OFFICE', o: [20, 11], s: [12, 10], floor: ['#9C7B50', '#93744B'], labelAt: [26, 17.5] },
  { id: 'devops', label: 'DEVOPS', o: [20, 21], s: [12, 11], floor: ['#8C7A66', '#857261'], labelAt: [26, 27.5] },
  { id: 'meeting_room', label: 'MEETING ROOM', o: [0, 20], s: [20, 12], floor: ['#53718B', '#4D6B85'], labelAt: [10, 30.4] },
]

/* ── Types ─────────────────────────────────────────────────────────── */

export interface WorldData {
  OX: number
  OY: number
  WW: number
  WH: number
}

export interface RoomBackground {
  id: string
  img: HTMLImageElement
  /** World-space x position (top-left of the image). */
  wx: number
  /** World-space y position (top-left of the image). */
  wy: number
  /** Depth value for draw ordering (rooms don't overlap, but kept for safety). */
  d: number
}

export interface WorldWithBackgrounds {
  backgrounds: RoomBackground[]
  bounds: WorldData
}

/* ── Calibration ───────────────────────────────────────────────────── */

/**
 * Per-room pixel offset from the image's top-left corner to the room's
 * isometric origin tile iso(o[0], o[1]).
 *
 * Generated by infra/scripts/normalize_rooms.py: room art is warped to the
 * canonical 64x32 projection (fit from each floor diamond), then the
 * calibration is derived from the canvas margins. Regenerate together with
 * footprints.generated.ts via extract_furniture.py.
 */
const CALIBRATION: Record<string, { dx: number; dy: number }> = {
  ceo_office:   { dx: 424, dy: 172 },
  managers:     { dx: 520, dy: 172 },
  dev_floor:    { dx: 680, dy: 173 },
  devops:       { dx: 487, dy: 172 },
  meeting_room: { dx: 423, dy: 173 },
}

/* ── World bounds (unchanged — uses ROOMS array) ───────────────────── */

export function worldBounds(): { minX: number; minY: number; w: number; h: number } {
  let minX = 1e9
  let minY = 1e9
  let maxX = -1e9
  let maxY = -1e9
  for (const r of ROOMS) {
    const [ox, oy] = r.o
    const [w, h] = r.s
    const corners: [number, number][] = [
      [ox - 1, oy - 1],
      [ox + w, oy - 1],
      [ox + w, oy + h],
      [ox - 1, oy + h],
    ]
    for (const [a, b] of corners) {
      const p = iso(a, b)
      minX = Math.min(minX, p.x)
      maxX = Math.max(maxX, p.x)
      minY = Math.min(minY, p.y - WALL_H)
      maxY = Math.max(maxY, p.y + 24)
    }
  }
  const pad = 40
  return { minX: minX - pad, minY: minY - pad, w: maxX - minX + pad * 2, h: maxY - minY + pad * 2 }
}

/* ── Image loader ──────────────────────────────────────────────────── */

function loadImage(src: string): Promise<HTMLImageElement> {
  return new Promise((resolve, reject) => {
    const img = new Image()
    img.onload = () => resolve(img)
    img.onerror = () => reject(new Error(`Failed to load room background: ${src}`))
    img.src = src
  })
}

/**
 * Load pre-rendered room background PNGs and compute their world-space
 * positions from the ROOMS array + CALIBRATION offsets.
 */
export async function loadRoomBackgrounds(): Promise<WorldWithBackgrounds> {
  const backgrounds: RoomBackground[] = []
  // dev-time cache bust: art is regenerated by infra scripts mid-session;
  // without this the browser serves stale PNGs for hours (import.meta.env
  // is statically replaced by vite: only DEV builds actually re-fetch).
  const bust = import.meta.env.DEV ? `?v=${Date.now()}` : ''

  for (const r of ROOMS) {
    const img = await loadImage(`/assets/office/rooms/${r.id}.png${bust}`)
    const origin = iso(r.o[0], r.o[1])
    const cal = CALIBRATION[r.id] ?? { dx: 0, dy: 0 }

    backgrounds.push({
      id: r.id,
      img,
      wx: origin.x - cal.dx,
      wy: origin.y - cal.dy,
      d: depth(r.o[0], r.o[1], 0),
    })
  }

  // Sort by depth so rooms that are "further back" draw first
  backgrounds.sort((a, b) => a.d - b.d)

  const b = worldBounds()
  return {
    backgrounds,
    bounds: {
      OX: -b.minX,
      OY: -b.minY,
      WW: Math.ceil(b.w),
      WH: Math.ceil(b.h),
    },
  }
}

/* ── Room labels (drawn per-frame on main canvas) ──────────────────── */

/**
 * Draw room labels and the "OFFICE SIMULATION" watermark on the main canvas.
 * Called each frame after room backgrounds, before employees.
 *
 * Labels are floor *markings*, not UI (docs/07 §6): dimmed, they never fight
 * the avatars for attention. The title lives in the void below-left of the
 * building — inside the walkable floor it collided with plates and sprites.
 */
export function drawRoomLabels(c: CanvasRenderingContext2D): void {
  c.textAlign = 'center'
  c.textBaseline = 'middle'

  for (const r of ROOMS) {
    const p = iso(r.labelAt[0], r.labelAt[1])
    c.font = '700 26px Archivo, sans-serif'
    c.fillStyle = 'rgba(0,0,0,.45)'
    c.fillText(r.label, p.x + 2, p.y + 2)
    c.fillStyle = 'rgba(255,255,255,.55)'
    c.fillText(r.label, p.x, p.y)
  }

  // Below-left of the meeting room — the one corner of the bounding box no
  // room, avatar, or name plate can ever reach.
  const g = iso(2.5, 34)
  c.font = '700 20px Archivo, sans-serif'
  ;(c as CanvasRenderingContext2D & { letterSpacing?: string }).letterSpacing = '3px'
  c.fillStyle = 'rgba(230,237,247,.30)'
  c.fillText('OFFICE SIMULATION', g.x, g.y)
  ;(c as CanvasRenderingContext2D & { letterSpacing?: string }).letterSpacing = '0px'
}
